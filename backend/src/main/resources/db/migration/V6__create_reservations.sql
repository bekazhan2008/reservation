CREATE TABLE reservations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              property_id BIGINT NOT NULL REFERENCES properties(id),
                              tenant_id BIGINT NOT NULL REFERENCES users(id),

                              start_date DATE NOT NULL,
                              end_date DATE NOT NULL,
                              months INTEGER NOT NULL,

                              price_per_month NUMERIC(15, 2) NOT NULL,
                              total_price NUMERIC(17, 2) NOT NULL,

                              status VARCHAR(16) NOT NULL DEFAULT 'PENDING',

                              created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

                              CONSTRAINT reservations_dates_check
                                  CHECK (end_date > start_date),

                              CONSTRAINT reservations_months_check
                                  CHECK (months > 0),

                              CONSTRAINT reservations_price_check
                                  CHECK (price_per_month > 0 AND total_price > 0),

                              CONSTRAINT reservations_status_check
                                  CHECK (status IN (
                                                    'PENDING',
                                                    'CONFIRMED',
                                                    'REJECTED',
                                                    'CANCELLED'
                                      ))
);

CREATE INDEX reservations_property_idx
    ON reservations(property_id);

CREATE INDEX reservations_tenant_idx
    ON reservations(tenant_id);