CREATE TABLE categories (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE properties (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            owner_id BIGINT NOT NULL REFERENCES users(id),
                            property_type_id BIGINT NOT NULL REFERENCES property_types(id),

                            title VARCHAR(200) NOT NULL,
                            description TEXT NOT NULL,
                            city VARCHAR(150) NOT NULL,

                            price_per_month NUMERIC(15, 2) NOT NULL,
                            area_sqm NUMERIC(12, 2) NOT NULL,
                            land_area_sotka NUMERIC(12, 2),

                            published BOOLEAN NOT NULL DEFAULT TRUE,
                            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

                            CONSTRAINT properties_price_positive
                                CHECK (price_per_month > 0),

                            CONSTRAINT properties_area_positive
                                CHECK (area_sqm > 0),

                            CONSTRAINT properties_land_area_positive
                                CHECK (land_area_sotka IS NULL OR land_area_sotka > 0)
);

CREATE TABLE property_categories (
                                     property_id BIGINT NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
                                     category_id BIGINT NOT NULL REFERENCES categories(id),

                                     PRIMARY KEY (property_id, category_id)
);

CREATE INDEX properties_owner_idx ON properties(owner_id);
CREATE INDEX properties_type_idx ON properties(property_type_id);
CREATE INDEX property_categories_category_idx
    ON property_categories(category_id);